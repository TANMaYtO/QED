"""Fast in-loop evaluator for circle packing (n=26).

Adapted from OpenEvolve circle packing example:
https://github.com/algorithmicsuperintelligence/openevolve
Licensed under the Apache License, Version 2.0 (the "License");
you may not use this file except in compliance with the License.

NOTE: This evaluator uses floating-point arithmetic with an epsilon tolerance.
fast evaluator only; never gates a claim.
Exact verification is performed by qed.trust using exact rational arithmetic.
"""

import os
import pickle
import subprocess
import sys
import tempfile
import time
from typing import Any

import numpy as np

# Target sum of radii from AlphaEvolve paper benchmark (used for fitness scaling)
TARGET_VALUE: float = float(os.environ.get("CIRCLE_PACKING_TARGET_VALUE", "2.635"))

# Floating-point tolerance for fast in-loop checks
# fast evaluator only; never gates a claim
FAST_EVAL_TOLERANCE: float = 1e-6


def validate_packing(centers: np.ndarray, radii: np.ndarray) -> bool:
    """Validate that circles stay inside the unit square and do not overlap.

    fast evaluator only; never gates a claim.
    """
    n: int = centers.shape[0]

    if np.isnan(centers).any() or np.isnan(radii).any():
        return False

    for i in range(n):
        if radii[i] < 0.0:
            return False

        x: float = float(centers[i, 0])
        y: float = float(centers[i, 1])
        r: float = float(radii[i])

        # fast evaluator only; never gates a claim
        if (
            (x - r < -FAST_EVAL_TOLERANCE)
            or (x + r > 1.0 + FAST_EVAL_TOLERANCE)
            or (y - r < -FAST_EVAL_TOLERANCE)
            or (y + r > 1.0 + FAST_EVAL_TOLERANCE)
        ):
            return False

    for i in range(n):
        for j in range(i + 1, n):
            dist: float = float(np.sqrt(np.sum((centers[i] - centers[j]) ** 2)))
            # fast evaluator only; never gates a claim
            if dist < radii[i] + radii[j] - FAST_EVAL_TOLERANCE:
                return False

    return True


def run_with_timeout(
    program_path: str, timeout_seconds: int = 30
) -> tuple[np.ndarray, np.ndarray, float]:
    """Run candidate program in an isolated subprocess with wall-clock timeout.

    Sanitizes environment variables to prevent access to secrets and API keys.
    """
    with tempfile.NamedTemporaryFile(suffix=".py", delete=False) as temp_script:
        runner_code: str = f"""import os
import pickle
import sys

sys.path.insert(0, os.path.dirname(r'{program_path}'))

try:
    util = __import__('importlib.util').util
    spec = util.spec_from_file_location('program', r'{program_path}')
    module = util.module_from_spec(spec)
    spec.loader.exec_module(module)
    centers, radii, sum_radii = module.run_packing()
    with open(r'{temp_script.name}.results', 'wb') as f:
        pickle.dump({{'centers': centers, 'radii': radii, 'sum_radii': sum_radii}}, f)
except Exception as exc:
    with open(r'{temp_script.name}.results', 'wb') as f:
        pickle.dump({{'error': str(exc)}}, f)
"""
        temp_script.write(runner_code.encode("utf-8"))
        temp_script_path: str = temp_script.name

    results_path: str = f"{temp_script_path}.results"

    # Sanitize environment: scrub secrets before launching candidate code
    clean_env: dict[str, str] = {
        k: v
        for k, v in os.environ.items()
        if not any(s in k.upper() for s in ["KEY", "SECRET", "TOKEN", "AUTH", "PASS"])
    }

    try:
        proc = subprocess.Popen(
            [sys.executable, temp_script_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=clean_env,
        )
        try:
            _, _ = proc.communicate(timeout=timeout_seconds)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
            raise TimeoutError(
                f"Subprocess exceeded wall-clock timeout of {timeout_seconds}s"
            )

        if os.path.exists(results_path):
            with open(results_path, "rb") as f:
                payload = pickle.load(f)
            if "error" in payload:
                raise RuntimeError(payload["error"])
            return payload["centers"], payload["radii"], float(payload["sum_radii"])
        raise RuntimeError("No output generated by candidate program subprocess")
    finally:
        if os.path.exists(temp_script_path):
            os.unlink(temp_script_path)
        if os.path.exists(results_path):
            os.unlink(results_path)


def evaluate(program_path: str) -> dict[str, Any]:
    """Evaluate candidate program with subprocess isolation and floating tolerance.

    fast evaluator only; never gates a claim.
    """
    start_time: float = time.time()
    try:
        centers, radii, reported_sum = run_with_timeout(
            program_path, timeout_seconds=30
        )
        centers_arr = np.array(centers, dtype=float)
        radii_arr = np.array(radii, dtype=float)

        if centers_arr.shape != (26, 2) or radii_arr.shape != (26,):
            return {
                "sum_radii": 0.0,
                "target_ratio": 0.0,
                "validity": 0.0,
                "eval_time": float(time.time() - start_time),
                "combined_score": 0.0,
                "error": "Invalid output shapes",
            }

        valid: bool = validate_packing(centers_arr, radii_arr)
        sum_radii: float = float(np.sum(radii_arr)) if valid else 0.0
        target_ratio: float = float(sum_radii / TARGET_VALUE) if valid else 0.0
        combined_score: float = target_ratio if valid else 0.0
        eval_time: float = float(time.time() - start_time)

        return {
            "sum_radii": sum_radii,
            "target_ratio": target_ratio,
            "validity": 1.0 if valid else 0.0,
            "eval_time": eval_time,
            "combined_score": combined_score,
        }
    except Exception as exc:
        return {
            "sum_radii": 0.0,
            "target_ratio": 0.0,
            "validity": 0.0,
            "eval_time": float(time.time() - start_time),
            "combined_score": 0.0,
            "error": str(exc),
        }


def evaluate_stage1(program_path: str) -> dict[str, Any]:
    """Stage 1 evaluation for cascading evaluation workflows."""
    return evaluate(program_path)


def evaluate_stage2(program_path: str) -> dict[str, Any]:
    """Stage 2 evaluation for cascading evaluation workflows."""
    return evaluate(program_path)
